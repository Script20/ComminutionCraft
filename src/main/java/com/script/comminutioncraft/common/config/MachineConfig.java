    private static void section(ModConfigSpec.Builder builder, String section, String title) {
        String key = "comminutioncraft.configuration." + section;
        LANG.add(new String[] {key, title});
        builder.comment(title).translation(key).push(section);
    }

    private static ConfigInt integer(ModConfigSpec.Builder builder, String section, String key, String name, String comment,
                                     int defaultValue) {
        String translation = translation(section, key, name, comment);
        return new ConfigInt(builder.comment(comment).translation(translation)
                .defineInRange(key, defaultValue, atLeastOne(key) ? 1 : 0, Integer.MAX_VALUE));
    }

    /** Times, sizes and ratios the code divides by can't be 0; costs, outputs and rates can (0 = free / none). */
    private static boolean atLeastOne(String key) {
        for (String part : new String[] {"processTime", "apacity", "energyPerMb", "energyPerHydrogen", "waterPerHydrogen",
                "waterPerDeuterium", "waterPerFilterWear", "pelletBurnTicks", "ignitionPlasmaPerTick", "TicksPerMb", "RingSide"}) {
            if (key.contains(part)) {
                return true;
            }
        }
        return false;
    }

    private static ConfigDouble decimal(ModConfigSpec.Builder builder, String section, String key, String name, String comment,
                                        double defaultValue) {
        String translation = translation(section, key, name, comment);
        return new ConfigDouble(builder.comment(comment).translation(translation)
                .defineInRange(key, defaultValue, 0.0, 1_000_000.0));
    }

    private static String translation(String section, String key, String name, String comment) {
        String translation = "comminutioncraft.configuration." + section + "." + key;
        LANG.add(new String[] {translation, name});
        LANG.add(new String[] {translation + ".tooltip", comment});
        return translation;
    }

    /** True once the server config is loaded (in a world); before that values read as their defaults. */
    static boolean loaded() {
        return SPEC != null && SPEC.isLoaded();
    }

